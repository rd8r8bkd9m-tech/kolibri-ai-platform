# Flatten
all_cities = []
for subject, cities in SUBJECTS.items():
    for name, coeff in cities:
        all_cities.append((name, coeff))

# Deduplicate
seen = set()
unique = []
for name, coeff in all_cities:
    if name not in seen:
        seen.add(name)
        unique.append((name, coeff))

print(f"Cities: {len(unique)}")

# Load base items
def load_json_files(base_dir):
    items = []
    for fname in os.listdir(base_dir):
        if not fname.endswith('.json'):
            continue
        try:
            with open(os.path.join(base_dir, fname)) as f:
                data = json.load(f)
                if isinstance(data, list):
                    for item in data:
                        items.append({
                            "code": item.get("code", ""),
                            "name": item.get("name", item.get("name_ru", "")),
                            "unit": item.get("unit", ""),
                            "price": str(item.get("price", item.get("price_rub", 0))),
                            "category": item.get("category", fname.split("_")[0]),
                            "source": item.get("source", fname),
                        })
        except: continue
    return items

Base.metadata.create_all(bind=engine)
db = SessionLocal()
db.query(CatalogItemDB).delete()
