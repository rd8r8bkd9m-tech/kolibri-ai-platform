base_items = load_json_files('/Users/kolibri/Downloads/Kimi_Agent_КолибриФин')
count = 0

for item in base_items:
    db.add(CatalogItemDB(id=str(uuid.uuid4()), code=item["code"], name=item["name"],
        unit=item["unit"], price=item["price"], category=item["category"],
        source=item["source"], region="Базовая", currency="RUB", is_active=True))
    count += 1

for item in base_items:
    try:
        bp = Decimal(item["price"])
    except:
        continue
    if bp <= 0:
        continue
    for city, coeff in unique:
        rp = (bp * Decimal(str(coeff))).quantize(Decimal("0.01"))
        db.add(CatalogItemDB(
            id=str(uuid.uuid4()),
            code=f"{item['code']}-{city[:3].lower()}",
            name=f"{item['name']} ({city})",
            unit=item["unit"], price=str(rp), category=item["category"],
            source=f"{item['source']} × {coeff}", region=city,
            currency="RUB", is_active=True,
        ))
        count += 1

db.commit()
total = db.query(CatalogItemDB).count()
regions = db.query(CatalogItemDB.region, func.count()).group_by(CatalogItemDB.region).all()
print(f"Total: {total}, Regions: {len(regions)}")
db.close()
